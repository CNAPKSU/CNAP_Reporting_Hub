# Builds search-index.js for the prototype's search box (MW 2026-11-15: "both" -> working search on every page).
# Indexes each page's title and its section headings, the member profiles, and the threads. Prototype only.
import re, glob, os, json, html
V = '/tmp/claude-0/hubproto/v4/'
SKIP = {'system.html', 'reporting-sketch.html', 'neurosync-flyer.html'}
items = []
def short(x, n=130):
    return x if len(x) <= n else x[:n].rsplit(' ', 1)[0] + '…'
def clean(x): return html.unescape(re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', x))).strip()
for path in sorted(glob.glob(V + '*.html')):
    f = os.path.basename(path)
    if f.startswith('_') or f in SKIP or re.match(r'reporting-\d+', f): continue
    s = open(path).read()
    m = re.search(r'<title>(.*?)</title>', s, re.S)
    title = clean(m.group(1)).replace(' · CNAP Member Hub', '') if m else f
    if f == 'index.html': title = 'Home'
    kind = 'Person' if f.startswith('member-') else 'Thread' if f.startswith('thread') and f != 'threads.html' else 'Page'
    lead = re.search(r'<p class="[^"]*(?:lead|mb-role)[^"]*">(.*?)</p>', s, re.S)
    items.append({'t': title, 'u': f, 'k': kind, 'd': short(clean(lead.group(1))) if lead else ''})
    if kind != 'Page': continue
    seen = set()
    for hm in re.finditer(r'<h([23])[^>]*\bid="([^"]+)"[^>]*>(.*?)</h\1>', s, re.S):
        t = clean(hm.group(3))
        if not t or t.lower() in seen or len(t) > 90: continue
        seen.add(t.lower())
        items.append({'t': t, 'u': f + '#' + hm.group(2), 'k': 'Section', 'd': title})

# Dates from Home's calendar list (deadlines, talks, Center events)
import datetime as _dt
_ix = open(V + 'index.html').read()
for d, tm, kind, name in re.findall(r"\['(\d{4}-\d{2}-\d{2})','([^']*)','(\w+)','([^']+)'\]", _ix):
    if kind == 'you': continue  # private meetings stay out of search
    day = _dt.date.fromisoformat(d)
    items.append({'t': html.unescape(name), 'u': 'events.html', 'k': 'Deadline' if kind == 'due' else 'Date', 'd': day.strftime('%A, %B ') + str(day.day) + ', ' + str(day.year) + (', ' + tm if tm else '')})
open(V + 'search-index.js', 'w').write('/* Generated by gen/searchidx.py. The prototype search list: pages, their sections, people, and threads. */\nwindow.HUB_SEARCH=' + json.dumps(items, ensure_ascii=False) + ';\n')
print('ok', len(items))
