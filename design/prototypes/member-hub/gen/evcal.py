# Copies Home's calendar (markup, styles, script) for the top of the Events page, so both show the
# same dates from one source. Styles are scoped under .ev-cal. MW 2026-11-15: "yes" to a month grid
# on Events with a Month/List toggle, and the menu item "Events calendar".
import re
V = '/tmp/claude-0/hubproto/v4/'
s = open(V + 'index.html').read()

# markup: filters + calendar, without Home's section header
i = s.index('aria-labelledby="cal-h"')
a = s.index('<div class="cal-filters"', i)
b = s.index('<div class="keys">', i)
mk = s[a:b].rstrip()
opened = len(re.findall(r'<div\b', mk)); closed = mk.count('</div>')
while closed > opened: mk = mk[:mk.rfind('</div>')].rstrip(); closed -= 1
mk += '</div>' * (opened - closed)

# script: the calendar block only, opening in Month view
j = s.index('/* calendar: prototype')
k = s.index("\n  try{var otp=document.querySelector('.otp')", j)
js = s[j:k].replace("var view='week',", "var view='month',", 1)
mk = mk.replace('<button type="button" data-v="month" aria-pressed="false">Month</button><button type="button" data-v="week" aria-pressed="true">Week</button>',
                '<button type="button" data-v="month" aria-pressed="true">Month</button><button type="button" data-v="week" aria-pressed="false">Week</button>')

mk = mk.replace('<button type="button" data-v="list" aria-pressed="false">List</button>', '')  # Events has its own List

# styles
css = ''.join(re.findall(r'<style[^>]*>(.*?)</style>', s, re.S))
css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
root = re.search(r':root\{([^}]*)\}', css).group(1)
TOK = ['cal', 'cal-filters', 'cal-month', 'cal-panel', 'cal-band', 'cd-empty', 'cd-ev', 'cd-head', 'ce', 'ce-more', 'ces', 'cf', 'ci',
       'cl-date', 'cl-day', 'cl-empty', 'cl-ev', 'cl-today', 'cm-day', 'cm-grid', 'cm-head', 'cm-nav', 'cm-tools', 'cm-views', 'ct',
       'd-num', 'd-wd', 'has', 'brk', 'today', 'sel', 'wd-l', 'wd-s', 'wk', 'wk-d', 'wk-evs', 'wk-h', 'wk-none', 'wk-wd', 'ym', 'ym-d',
       'ym-g', 'ym-w', 'yr', 'arrow', 'mks', 'tm', 'past', 'k-ns', 'k-ctr', 'k-due', 'k-you', 'k-cam', 'kind', 'dbtn']
pat = re.compile(r'\.(' + '|'.join(re.escape(t) for t in sorted(TOK, key=len, reverse=True)) + r')(?![\w-])')
def parse(t):
    out = []; i = 0; n = len(t)
    while i < n:
        j = t.find('{', i)
        if j < 0: break
        sel = t[i:j].strip(); d = 1; k = j + 1
        while d:
            if t[k] == '{': d += 1
            elif t[k] == '}': d -= 1
            k += 1
        out.append((sel, t[j + 1:k - 1])); i = k
    return out
def scope(sel):
    keep = [x.strip() for x in sel.split(',') if pat.search(x) and not x.strip().startswith((':root', 'html', '.cal-band'))]
    return ','.join('.ev-cal.ev-cal ' + x for x in keep)   # doubled class: Home's rules outrank guide.css
res = []
for sel, body in parse(css):
    if sel.startswith(('@media', '@supports')):
        inner = [f'{scope(x)}{{{y}}}' for x, y in parse(body) if scope(x)]
        if inner: res.append(sel + '{' + ''.join(inner) + '}')
    elif not sel.startswith('@'):
        sc = scope(sel)
        if sc: res.append(f'{sc}{{{body}}}')
out = ('/* Calendar copied from Home for the Events page. Generated by gen/evcal.py from index.html; do not edit by hand. */\n'
       '.ev-cal{' + root + '}\n'
       '.ev-cal .cm-tools{justify-content:flex-end}\n'
       '.ev-cal .cal-filters{margin-bottom:20px}\n'
       '.ev-cal .cal{margin-top:0}\n.ev-cal .lead{font:inherit;color:inherit;margin:0;max-width:none;letter-spacing:inherit}\n.ev-mode{align-self:flex-start;width:max-content;max-width:100%}\n.ev-cal .today{top:auto;transform:none;flex-direction:column;align-items:stretch;pointer-events:auto}\n.ev-cal .today span{font-size:inherit;font-weight:inherit;color:inherit;transform:none}\n.ev-cal .today::after{content:none}\n@media (max-width:980px){.ev-cal .today{display:flex}}\n'
       + '\n'.join(res))
open(V + 'evcal.css', 'w').write(out)
SNIP = {'markup': mk, 'script': js}
if __name__ == '__main__':
    print('ok', len(res), 'rules')
